# Packs the Clawd parts from clawd_render into 4-bit sprites for the clock (src/clawd_sprites.h).
#   python3 make_sprites.py <render-dir> <out.h> <render-txt>
# Each pixel becomes one of 16 values: 0 transparent, 1-12 brightness level (fully covered),
# 13-15 edge pixels with 30/55/80 % coverage. The colors are applied on the clock (scene.h).
import sys, os
src, out, info = sys.argv[1], sys.argv[2], sys.argv[3]
def rd(p):
    d=open(p,'rb').read(); parts=d.split(b'\n',1); h=parts[0].split()
    return int(h[1]), int(h[2]), parts[1]
parts=['body','armL','armR','leg0','leg1','leg2','leg3']
lines=['// Generated by sim/make_sprites.py from sim/clawd_render.cpp and the Clawd model (Bambu-Clawd STL).',
       '// Do not edit by hand. 4 bits per pixel, two pixels per byte (high nibble first).',
       '#pragma once', '#include <stdint.h>', '#ifndef PROGMEM', '#define PROGMEM', '#endif', '',
       'struct ClawdSprite { int16_t x, y, w, h; const uint8_t *px; };', '']
total=0
for p in parts:
    W,H,cov=rd(os.path.join(src,f'p_{p}.pgm')); _,_,shd=rd(os.path.join(src,f'p_{p}.shd'))
    xs=[i%W for i in range(W*H) if cov[i]>=40]; ys=[i//W for i in range(W*H) if cov[i]>=40]
    x0,x1,y0,y1=min(xs),max(xs),min(ys),max(ys)
    w,h=x1-x0+1,y1-y0+1
    idx=[]
    for y in range(y0,y1+1):
        for x in range(x0,x1+1):
            c=cov[y*W+x]; s=shd[y*W+x]/255
            if c<40: v=0
            elif c<110: v=13
            elif c<170: v=14
            elif c<200: v=15
            else: v=1+max(0,min(11,round((s-0.30)/0.70*11)))
            idx.append(v)
    if w%2: idx=[v for r in range(h) for v in idx[r*w:(r+1)*w]+[0]]; wp=w+1
    else: wp=w
    data=bytes((idx[i]<<4)|idx[i+1] for i in range(0,len(idx),2))
    total+=len(data)
    nm=p.upper()
    lines.append(f'static const uint8_t CLAWD_{nm}_PX[{len(data)}] PROGMEM = {{')
    for i in range(0,len(data),24): lines.append('  '+','.join(str(b) for b in data[i:i+24])+',')
    lines.append('};')
    lines.append(f'static const ClawdSprite CLAWD_{nm} = {{{x0}, {y0}, {wp}, {h}, CLAWD_{nm}_PX}};')
    lines.append('')
eyes=[l.split() for l in open(info) if l.startswith('eye')]
W,H=open(info).readline().split()[:2]
lines.append(f'static const int CLAWD_W = {W}, CLAWD_H = {H};   // frame of the whole figure')
for e in eyes:
    lines.append(f'static const int CLAWD_EYE{e[1]}_X = {round(float(e[2]))}, CLAWD_EYE{e[1]}_Y = {round(float(e[3]))};')
lines.append(f'// Total {total} bytes')
open(out,'w').write('\n'.join(lines)+'\n')
print('wrote', out, total, 'bytes')
